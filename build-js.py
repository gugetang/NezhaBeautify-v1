#!/usr/bin/env python3
"""Build NezhaBeautify.js (script-src version) from NezhaBeautify.html.

Usage: python3 build-js.py
Reads NezhaBeautify.html in the same directory and writes NezhaBeautify.js.
The .js file is a self-contained IIFE: it injects the CSS + HTML nodes,
loads Globe.GL dynamically (replacing the <script src="//unpkg.com/globe.gl">
tag in the HTML version), then runs the same inline script (CONFIG + logic).
That makes the project loadable from Nezha v1 custom_code with one line:
  <script src="https://cdn.jsdelivr.net/gh/gugetang/NezhaBeautify-v1@main/NezhaBeautify.js"></script>
Config override (optional, before the script tag):
  <script>window.NezhaBeautifyConfig = { finance: { prices: {} } };</script>
Note: the HTML version is still the source of truth; do not edit the .js
by hand, edit NezhaBeautify.html and rebuild.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "NezhaBeautify.html"
DST = HERE / "NezhaBeautify.js"

text = SRC.read_text(encoding="utf-8")

m_style = re.search(r"^<style>(.*?)</style>", text, re.S | re.M)
m_ext = re.search(r'^<script\s+src="([^"]+)"></script>', text, re.M)
m_inline = re.findall(r"^<script>(.*?)</script>", text, re.S | re.M)
if not m_style or not m_ext or len(m_inline) != 1:
    sys.exit(
        f"unexpected structure: style={bool(m_style)} "
        f"ext={m_ext.group(1) if m_ext else None} inline_scripts={len(m_inline)}"
    )

css = m_style.group(1).strip("\n")
globe_src = m_ext.group(1)
# HTML nodes: between </style> and the external <script src=...>
html = text[m_style.end() : m_ext.start()].strip()
main_js = m_inline[0].strip("\n")

header = """// NezhaBeautify v1 — script-src version, generated from NezhaBeautify.html
// Generated by build-js.py — do not edit by hand, edit NezhaBeautify.html and rebuild.
// Load from Nezha v1 custom_code with one line:
//   <script src="https://cdn.jsdelivr.net/gh/gugetang/NezhaBeautify-v1@main/NezhaBeautify.js"></script>
// Optional config override, before that line:
//   <script>window.NezhaBeautifyConfig = { finance: { prices: {} } };</script>
(function () {
  'use strict';
  // Avoid double injection when custom_code is re-applied in the same page.
  if (document.getElementById('welcome-bubble-container')) return;
  var CSS = %s;
  var HTML = %s;
  var GLOBE_SRC = %s;
  function inject() {
    if (!document.getElementById('nezha-beautify-style')) {
      var st = document.createElement('style');
      st.id = 'nezha-beautify-style';
      st.textContent = CSS;
      document.head.appendChild(st);
    }
    var tmp = document.createElement('div');
    tmp.innerHTML = HTML;
    while (tmp.firstChild) document.body.appendChild(tmp.firstChild);
    // Globe.GL is only used lazily when the earth modal opens (the code
    // checks typeof Globe === 'undefined'), so load it in the background
    // instead of blocking on it, like the <script src> tag in the HTML version.
    if (typeof Globe === 'undefined' && !document.querySelector('script[data-nezha-beautify-globe]')) {
      var s = document.createElement('script');
      s.setAttribute('data-nezha-beautify-globe', '1');
      s.src = GLOBE_SRC;
      s.async = true;
      document.head.appendChild(s);
    }
  }
  function run() {
    inject();
%s
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', run);
  } else {
    run();
  }
})();
""" % (
    json.dumps(css, ensure_ascii=False),
    json.dumps(html, ensure_ascii=False),
    json.dumps(globe_src, ensure_ascii=False),
    main_js,
)

DST.write_text(header, encoding="utf-8")
print(f"wrote {DST} ({DST.stat().st_size} bytes)")
